CREATE TABLE IF NOT EXISTS gold_air_quality (

  city TEXT NOT NULL,
  timestamp TIMESTAMPTZ NOT NULL,
  aqi NUMERIC NOT NULL,
  co NUMERIC NOT NULL,
  no NUMERIC NOT NULL,
  no2 NUMERIC NOT NULL,
  o3 NUMERIC NOT NULL,
  so2 NUMERIC NOT NULL,
  pm2_5 NUMERIC NOT NULL,
  pm10 NUMERIC NOT NULL,
  nh3 NUMERIC NOT NULL,
  category TEXT NOT NULL,
  score NUMERIC NOT NULL,

  PRIMARY KEY (city, timestamp)
);